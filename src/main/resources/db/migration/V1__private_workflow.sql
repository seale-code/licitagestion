CREATE TABLE app_user (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL,
 role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN','GESTOR','CONSULTA')),
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 phone VARCHAR(20) NOT NULL DEFAULT '',
 whatsapp_opt_in BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE tender (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(80) NOT NULL UNIQUE,
 title VARCHAR(240) NOT NULL,
 entity VARCHAR(200) NOT NULL,
 description TEXT NOT NULL,
 published_on DATE NOT NULL,
 deadline TIMESTAMP WITH TIME ZONE NOT NULL,
 status VARCHAR(40) NOT NULL CHECK (status IN ('RECIBIDA','EN_REVISION','EN_PREPARACION','PENDIENTE_DOCUMENTOS','LISTA_PARA_PRESENTAR','PRESENTADA','ADJUDICADA','NO_ADJUDICADA','CANCELADA')),
 priority VARCHAR(10) NOT NULL CHECK (priority IN ('ALTA','MEDIA','BAJA')),
 owner_id BIGINT NOT NULL REFERENCES app_user(id),
 notes TEXT NOT NULL DEFAULT '',
 version INTEGER NOT NULL DEFAULT 0,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_tender_deadline ON tender(status, deadline);
CREATE TABLE tender_access (
 tender_id BIGINT NOT NULL REFERENCES tender(id),
 user_id BIGINT NOT NULL REFERENCES app_user(id),
 PRIMARY KEY(tender_id,user_id)
);
CREATE TABLE document (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tender_id BIGINT NOT NULL REFERENCES tender(id),
 name VARCHAR(200) NOT NULL,
 kind VARCHAR(40) NOT NULL,
 storage_key VARCHAR(80) NOT NULL UNIQUE,
 mime VARCHAR(80) NOT NULL,
 size_bytes BIGINT NOT NULL,
 sha256 VARCHAR(64) NOT NULL,
 extracted_text TEXT NOT NULL,
 extraction_status VARCHAR(40) NOT NULL,
 uploaded_by BIGINT NOT NULL REFERENCES app_user(id),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_document_tender ON document(tender_id);
CREATE TABLE requirement (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tender_id BIGINT NOT NULL REFERENCES tender(id),
 description VARCHAR(1500) NOT NULL,
 kind VARCHAR(40) NOT NULL,
 status VARCHAR(20) NOT NULL CHECK (status IN ('PENDIENTE','EN_PROGRESO','COMPLETADO','NO_APLICA')),
 owner_id BIGINT NOT NULL REFERENCES app_user(id),
 deadline TIMESTAMP WITH TIME ZONE NOT NULL,
 document_id BIGINT REFERENCES document(id),
 notes TEXT NOT NULL DEFAULT '',
 source VARCHAR(40) NOT NULL DEFAULT 'MANUAL',
 source_reference VARCHAR(200) NOT NULL DEFAULT '',
 version INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX ix_requirement_tender ON requirement(tender_id);
CREATE TABLE task (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tender_id BIGINT NOT NULL REFERENCES tender(id),
 requirement_id BIGINT UNIQUE REFERENCES requirement(id),
 name VARCHAR(200) NOT NULL,
 description TEXT NOT NULL DEFAULT '',
 owner_id BIGINT NOT NULL REFERENCES app_user(id),
 deadline TIMESTAMP WITH TIME ZONE NOT NULL,
 priority VARCHAR(10) NOT NULL CHECK (priority IN ('ALTA','MEDIA','BAJA')),
 status VARCHAR(20) NOT NULL CHECK (status IN ('PENDIENTE','EN_PROGRESO','COMPLETADA')),
 notes TEXT NOT NULL DEFAULT '',
 version INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX ix_task_tender_deadline ON task(tender_id, deadline);
CREATE TABLE milestone (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tender_id BIGINT NOT NULL REFERENCES tender(id),
 name VARCHAR(200) NOT NULL,
 kind VARCHAR(40) NOT NULL,
 deadline TIMESTAMP WITH TIME ZONE NOT NULL,
 owner_id BIGINT NOT NULL REFERENCES app_user(id),
 completed BOOLEAN NOT NULL DEFAULT FALSE,
 notes TEXT NOT NULL DEFAULT '',
 version INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX ix_milestone_tender_deadline ON milestone(tender_id, deadline);
CREATE TABLE analysis_run (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 document_id BIGINT NOT NULL REFERENCES document(id),
 provider VARCHAR(100) NOT NULL,
 summary TEXT NOT NULL,
 created_by BIGINT NOT NULL REFERENCES app_user(id),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE suggestion (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 analysis_id BIGINT NOT NULL REFERENCES analysis_run(id),
 kind VARCHAR(40) NOT NULL,
 description VARCHAR(1500) NOT NULL,
 source_reference VARCHAR(200) NOT NULL,
 source_quote VARCHAR(2000) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE' CHECK(status IN ('PENDIENTE','ACEPTADA','DESCARTADA')),
 requirement_id BIGINT REFERENCES requirement(id),
 milestone_id BIGINT REFERENCES milestone(id)
);
CREATE TABLE chat_message (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tender_id BIGINT NOT NULL REFERENCES tender(id),
 user_id BIGINT NOT NULL REFERENCES app_user(id),
 question VARCHAR(1500) NOT NULL,
 answer TEXT NOT NULL,
 citations TEXT NOT NULL,
 provider VARCHAR(100) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE audit_event (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id BIGINT REFERENCES app_user(id),
 tender_id BIGINT REFERENCES tender(id),
 action VARCHAR(100) NOT NULL,
 detail VARCHAR(500) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE notification (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tender_id BIGINT NOT NULL REFERENCES tender(id),
 recipient_id BIGINT NOT NULL REFERENCES app_user(id),
 alert_key VARCHAR(180) NOT NULL,
 alert_fingerprint VARCHAR(64) NOT NULL,
 phone VARCHAR(20) NOT NULL,
 body VARCHAR(1000) NOT NULL,
 status VARCHAR(30) NOT NULL CHECK(status IN ('BORRADOR','SIMULADA','ENVIANDO','ACEPTADA_META','ERROR','INCIERTA')),
 external_id VARCHAR(200) NOT NULL DEFAULT '',
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 sent_at TIMESTAMP WITH TIME ZONE,
 UNIQUE(alert_key, recipient_id, alert_fingerprint)
);

